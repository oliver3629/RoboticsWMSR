ROOT = Path(__file__).resolve().parent
CONSTANTS = {"N", "DT", "DURATION", "ATTACK_START", "ATTACKER", "ATTACK_TARGET", "PROJECTION",
             "SAFETY_RADIUS", "MAX_SI_SPEED", "BLEND", "COMMUNICATION_EVERY"}
FUNCTIONS = {"initial_state", "complete_neighbors", "consensus_round", "create_motion_functions", "motion_command"}


def selected_source(path, names, include_constants=False):
    source = path.read_text(encoding="utf-8")
    pieces = []
    for node in ast.parse(source).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in names:
            pieces.append(ast.get_source_segment(source, node))
        elif include_constants and isinstance(node, ast.Assign):
            if any(isinstance(target, ast.Name) and target.id in CONSTANTS for target in node.targets):
                pieces.append(ast.get_source_segment(source, node))
    return "\n\n".join(pieces)


